package dev.opengarmin.app.i18n

import java.util.Locale

/**
 * Translation catalog for the whole app.
 *
 * English is the source language: keys are the exact English strings used in
 * the UI, so an untranslated string always renders correctly instead of
 * showing a raw key. To add a language, add an [AppLanguage] entry and a map
 * here. To translate new copy, add its English source string as the key.
 *
 * Dynamic copy uses Formatter placeholders (%s, %d, %%) and is rendered with
 * [format]. Positional placeholders (%1$s) let translations reorder words.
 */
object AppStrings {

    private val catalogs: Map<AppLanguage, Map<String, String>> by lazy {
        mapOf(AppLanguage.ITALIAN to Italian)
    }

    fun translate(text: String, language: AppLanguage): String {
        val target = language.resolve()
        if (target == AppLanguage.ENGLISH) return text
        return catalogs[target]?.get(text) ?: text
    }

    fun format(text: String, language: AppLanguage, vararg args: Any?): String {
        val template = translate(text, language)
        if (args.isEmpty()) return template
        return String.format(localeFor(language), template, *args)
    }

    private fun localeFor(language: AppLanguage): Locale = when (language.resolve()) {
        AppLanguage.ITALIAN -> Locale.ITALIAN
        else -> Locale.ENGLISH
    }

    /** Exposed for catalog validation tests. */
    internal fun catalogFor(language: AppLanguage): Map<String, String> =
        catalogs[language.resolve()] ?: emptyMap()

